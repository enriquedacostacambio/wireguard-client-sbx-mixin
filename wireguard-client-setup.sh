#!/bin/sh
set -e

CONFIG_ARG="$1"
if [ -z "${CONFIG_ARG}" ]; then
    echo "Error: WireGuard client configuration not passed.'" >&2
    exit 1
fi

CONFIG_FILE_1=/dev/shm/wg0.conf
CONFIG_FILE_2=/tmp/wg0.conf
CONFIG_FILE=${CONFIG_FILE_1}
[ -f ${CONFIG_FILE} ] || CONFIG_FILE=${CONFIG_FILE_2}

safe_delete() {
	local file=$1
    if [ -f "${file}" ]; then
    	: > ${file}
    	dd if=/dev/zero of=${file} bs=1M count=$(du -m ${file} | cut -f1) conv=notrunc status=none
    	sync
        rm -f ${file}
    fi
}
cleanup() {
    safe_delete ${CONFIG_FILE_1}
    safe_delete ${CONFIG_FILE_2}
}
trap cleanup EXIT INT TERM

# Write the config
cleanup
touch ${CONFIG_FILE}
chmod 600 ${CONFIG_FILE}
echo "${CONFIG_ARG}" > ${CONFIG_FILE}


# Sign the current resolv.conf file so it can be modified
echo "# Generated by resolvconf" > /etc/resolv.conf.signed
cat /etc/resolv.conf >> /etc/resolv.conf.signed
mv /etc/resolv.conf.signed /etc/resolv.conf

# Start WG
WG_QUICK_USERSPACE_IMPLEMENTATION=wireguard wg-quick up ${CONFIG_FILE}

# Delete config file
cleanup
